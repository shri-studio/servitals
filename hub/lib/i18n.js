// the string for key, with {name} filled from vars; an unknown key shows as itself
function tr(key, vars) {
  const s = Object.prototype.hasOwnProperty.call(STRINGS, key) ? STRINGS[key] : key;
  return vars ? s.replace(/\{(\w+)\}/g, (m, k) => (Object.prototype.hasOwnProperty.call(vars, k) ? String(vars[k]) : m)) : s;
}

if (typeof module === "object" && module.exports) module.exports = { STRINGS, tr };
